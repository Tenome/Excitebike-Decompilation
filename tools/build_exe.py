#!/usr/bin/env python3
"""Build a PRIVATE, self-contained Excitebike program from your own ROM files.

The ROM data is read from your .nes files at build time and compiled into the program (and into the editors' data file), so the result runs without any ROM file.
It contains game data: keep it for your own use and never upload or share it. (The repository and its CI never contain such a build.)

  python tools/build_exe.py [--us orig/excitebike_us.nes] [--eu orig/excitebike_eu.nes] [--sdl-dir DIR] [--out dist/Excitebike] [--clang PATH]

Needs a C compiler (clang or gcc) and the SDL2 development files: on Windows the SDL2 "devel" folder with include/ and lib/x64/ (pass --sdl-dir or set SDL2_DIR);
on Linux/macOS sdl2-config is used. One ROM is enough; with both, start the program with --region eu (or put region=eu in excitebike.cfg) for the PAL version."""
import argparse, os, shutil, subprocess, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
ap = argparse.ArgumentParser()
ap.add_argument('--us', default=os.path.join(ROOT, 'orig', 'excitebike_us.nes')); ap.add_argument('--eu', default=os.path.join(ROOT, 'orig', 'excitebike_eu.nes'))
ap.add_argument('--sdl-dir', default=os.environ.get('SDL2_DIR')); ap.add_argument('--out', default=os.path.join(ROOT, 'dist', 'Excitebike')); ap.add_argument('--clang')
a = ap.parse_args()
WIN = os.name == 'nt'

def find_cc():
    for c in (a.clang, os.environ.get('CLANG'), 'clang', 'gcc', 'cc'):
        if c and shutil.which(c): return c
    sys.exit('no C compiler found (pass --clang PATH)')
CC = find_cc()

roms = {k: getattr(a, k) for k in ('us', 'eu') if os.path.isfile(getattr(a, k))}
if not roms: sys.exit('no ROM found: put your Excitebike ROM(s) in orig/ as excitebike_us.nes / excitebike_eu.nes or pass --us / --eu')
print('ROMs:', ', '.join('%s=%s' % kv for kv in roms.items()))

# 1. the ROM data as C arrays (in build/, which git ignores)
os.makedirs(os.path.join(ROOT, 'build'), exist_ok=True)
gen = os.path.join(ROOT, 'build', 'embedded_rom.c'); lines = ['/* generated by tools/build_exe.py from your own ROM files: private, do not share */']
for k in ('us', 'eu'):
    d = open(roms[k], 'rb').read() if k in roms else b''
    if d and d[:4] != b'NES\x1a': sys.exit(roms[k] + ' is not an iNES ROM')
    lines.append('const unsigned char g_rom_%s[] = {' % k + ('\n' + ',\n'.join(','.join(str(b) for b in d[i:i + 24]) for i in range(0, len(d), 24)) if d else '0') + '\n};')
    lines.append('const unsigned int g_rom_%s_len = %d;' % (k, len(d)))
open(gen, 'w').write('\n'.join(lines) + '\n')

# 2. compile the game
out = os.path.abspath(a.out); shutil.rmtree(out, ignore_errors=True); os.makedirs(out)
exe = os.path.join(out, 'excitebike.exe' if WIN else 'excitebike')
src = [os.path.join(ROOT, 'port', f) for f in ('main.c', 'ppu.c', 'apu.c', 'audiomod.c')] + [os.path.join(ROOT, 'c', 'excitebike.c'), gen]
common = ['-O2', '-DEMBED_ROM', '-Wno-unused-label', '-Wno-unused-function', '-Wno-unused-variable']
if WIN:
    if not a.sdl_dir: sys.exit('pass --sdl-dir (the SDL2 development folder with include/ and lib/x64/) or set SDL2_DIR')
    sdl = os.path.abspath(a.sdl_dir)
    cmd = [CC] + common + ['-o', exe] + src + ['-I' + os.path.join(sdl, 'include'), '-L' + os.path.join(sdl, 'lib', 'x64'), '-lSDL2', '-Wl,/subsystem:windows', '-Wl,/entry:mainCRTStartup']
else:
    cfg = subprocess.check_output(['sdl2-config', '--cflags', '--libs'], text=True).split()
    cmd = [CC, '-std=gnu11'] + common + ['-o', exe] + src + cfg + ['-lm']
print('compiling the game...'); subprocess.check_call(cmd)
if WIN:
    shutil.copy(os.path.join(sdl, 'lib', 'x64', 'SDL2.dll'), out)
    print('compiling the editors launcher...')
    subprocess.check_call([CC, '-O2', '-o', os.path.join(out, 'excitebike-editors.exe'), os.path.join(ROOT, 'port', 'editors.c'), '-luser32', '-lshell32', '-Wl,/subsystem:windows'])

# 3. the editors: scripts, pages and a data file made from the ROM (also private)
tools = os.path.join(out, 'tools'); os.makedirs(os.path.join(tools, 'editor'))
for f in ('ebdesign.py', 'ebmusic.py', 'chrbmp.py', 'levelpack.py'): shutil.copy(os.path.join(ROOT, 'tools', f), tools)
for f in ('index.html', 'tiles.html', 'music.html', 'serve.py'): shutil.copy(os.path.join(ROOT, 'tools', 'editor', f), os.path.join(tools, 'editor'))
import ebdesign, json
ebdesign.ROM_PATH = roms.get('us') or roms['eu']
ppu = os.path.join(ROOT, 'build', 'private_race.ppu')
subprocess.run([exe, '--frames', '1500', '--press', '200=08,260=01', '--shot', os.path.join(ROOT, 'build', 'private_tmp.bmp'), '--dump-ppu', ppu], capture_output=True)
open(os.path.join(tools, 'editor', 'data.js'), 'w').write('window.EB_DATA = ' + json.dumps(ebdesign.editor_data(ppu if os.path.exists(ppu) else None)) + ';\n')
os.makedirs(os.path.join(out, 'mods', 'audio'))
shutil.copy(os.path.join(ROOT, 'port', 'excitebike.cfg.example'), out)
shutil.copy(os.path.join(ROOT, 'port', 'README.md'), os.path.join(out, 'README.md'))
open(os.path.join(out, 'mods', 'audio', 'README.txt'), 'w').write('Put WAV files and .ebm songs here (see README.md); the game loads them at start, F6 reloads.\n')
open(os.path.join(out, 'PRIVATE.txt'), 'w').write('This folder is a private build: excitebike.exe and tools/editor/data.js contain data from your own Excitebike ROM(s).\nIt needs no ROM file. Use it yourself; do not upload or share it.\nTab opens the options menu. excitebike-editors.exe opens the editors (needs Python 3).\n')
print('built', out)
