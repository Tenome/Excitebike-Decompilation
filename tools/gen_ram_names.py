#!/usr/bin/env python3
"""Generate c/ram_names.h from config/us/ram.json: every named RAM address becomes a macro for the lifted C code.
Arrays (the four-rider arrays, timers, buffers) are function-like (RiderXLo(x)), single variables are object-like (RaceStarted).
With --rewrite the numeric RAM(0x..) accesses in c/*.c and c/*.inc are replaced by these names (the generated header is idempotent)."""
import json, os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
names = {int(k, 16): v for k, v in json.load(open(os.path.join(ROOT, 'config', 'us', 'ram.json'))).items()}
ARRAYS = {n for a, n in names.items() if n.startswith('Rider')} | {'RandomState', 'Timers', 'OamBuffer', 'PpuBuffer', 'BestTimes', 'SavedTimes', 'TrackDesign', 'TrackDesignWork'}
out = ['/* Generated by tools/gen_ram_names.py from config/us/ram.json: names for the game\'s RAM. Arrays take an index: RiderXLo(x) is the X low byte of rider x. */']
for a in sorted(names):
    n = names[a]
    if n in ARRAYS: out.append(f'#define {n}(i) RAM(0x{a:04X} + (i))')
    else: out.append(f'#define {n} RAM(0x{a:04X})')
open(os.path.join(ROOT, 'c', 'ram_names.h'), 'w', newline='\n').write('\n'.join(out) + '\n')
if '--rewrite' in sys.argv:
    arr = {a: n for a, n in names.items() if n in ARRAYS}; sc = {a: n for a, n in names.items() if n not in ARRAYS}
    total = 0
    for f in ('excitebike.c', 'sound.inc', 'extra_riders.inc'):
        p = os.path.join(ROOT, 'c', f); s = open(p, newline='').read(); nl = '\r\n' if '\r\n' in s else '\n'; s = s.replace('\r\n', '\n')
        def idx(m):
            global total
            a = int(m.group(1), 16)
            if a in arr and '(' not in m.group(2): total += 1; return f'{arr[a]}({m.group(2)})'
            return m.group(0)
        s = re.sub(r'RAM\((0x[0-9A-Fa-f]+) \+ ([^()]+?)\)', idx, s)
        def exact(m):
            global total
            a = int(m.group(1), 16)
            if a in sc: total += 1; return sc[a]
            if a in arr: total += 1; return f'{arr[a]}(0)'
            return m.group(0)
        s = re.sub(r'RAM\((0x[0-9A-Fa-f]+)\)', exact, s)
        open(p, 'w', newline='').write(s.replace('\n', nl))
    print('rewrote', total, 'accesses')
