/* Hardware registers ($2000-$7FFF): writes are logged in order, reads come from g_io_reads. The tests compare the log with the
 * writes the original code makes; the real port replaces these two functions with the PPU/APU/input layer. */
IoWrite g_io_log[8192];
int g_io_n;
uint8_t g_io_reads[0x8000];
int g_io_model;                               /* 1 = simple hardware model for whole-game runs: $2002 toggles its bits, joypads shift out g_pad_buttons */
uint8_t g_pad_buttons[2], g_pad_shift[2];
static uint32_t g_ppu_status_reads;
/* Host hooks (the PC port installs them; the tests leave them NULL): every register write and read, and timing events from the code's busy-wait loops. */
void (*g_hal_write)(uint16_t addr, uint8_t val);
uint8_t (*g_hal_read)(uint16_t addr);
void (*g_hal_event)(int event, int arg);
int (*g_hal_sound)(int chan, int value);
static inline void io_w(uint16_t a, uint8_t v) {
    if (g_hal_write) g_hal_write(a, v);
    if (g_io_n < 8192) { g_io_log[g_io_n].addr = a; g_io_log[g_io_n].val = v; g_io_n++; }
    if (g_io_model && a == 0x4016 && !(v & 1)) { g_pad_shift[0] = g_pad_buttons[0]; g_pad_shift[1] = g_pad_buttons[1]; }   /* strobe latches the buttons */
}
static inline uint8_t io_r(uint16_t a) {
    if (g_hal_read) return g_hal_read(a);
    if (g_io_model) {
        if (a == 0x2002) { uint8_t c = (uint8_t)g_ppu_status_reads++; return (uint8_t)(((c & 1) << 6) | (((c >> 1) & 1) << 7)); }
        if (a == 0x4016 || a == 0x4017) { int p = a & 1; uint8_t v = g_pad_shift[p] & 1; g_pad_shift[p] = (uint8_t)((g_pad_shift[p] >> 1) | 0x80); return v; }
    }
    return g_io_reads[a & 0x7FFF];
}

/* ---- CPU state and helpers for the mechanically lifted routines (c/auto_*.inc, generated by tools/lift6502.py) ---- */
static uint8_t ra, rx, ry, fc, fz, fn, fv, g_stk[256], g_sp = 0xFF;
static inline uint8_t RD(uint16_t a) { return a < 0x2000 ? g_ram[a & 0x7FF] : (a >= 0x8000 ? g_prg[a & 0x3FFF] : io_r(a)); }
static inline void WR(uint16_t a, uint8_t v) { if (a < 0x2000) g_ram[a & 0x7FF] = v; else if (a < 0x8000) io_w(a, v); }
static inline uint16_t zp_ptr(uint8_t p) { return (uint16_t)(g_ram[p] | g_ram[(uint8_t)(p + 1)] << 8); }
#define SETNZ(v) do { uint8_t v_ = (uint8_t)(v); fz = v_ == 0; fn = v_ >> 7; } while (0)
static inline void ADC(uint8_t m) { unsigned t = ra + m + fc; fv = ((~(ra ^ m) & (ra ^ t) & 0x80) != 0); fc = t > 0xFF; ra = (uint8_t)t; SETNZ(ra); }
static inline void SBC(uint8_t m) { ADC((uint8_t)(m ^ 0xFF)); }
static inline void CMP(uint8_t r, uint8_t m) { fc = r >= m; SETNZ((uint8_t)(r - m)); }
static inline void BIT(uint8_t m) { fz = (ra & m) == 0; fn = m >> 7; fv = (m >> 6) & 1; }
static inline uint8_t SHIFT_ASL(uint8_t v) { fc = v >> 7; v = (uint8_t)(v << 1); SETNZ(v); return v; }
static inline uint8_t SHIFT_LSR(uint8_t v) { fc = v & 1; v >>= 1; SETNZ(v); return v; }
static inline uint8_t SHIFT_ROL(uint8_t v) { uint8_t c = fc; fc = v >> 7; v = (uint8_t)((v << 1) | c); SETNZ(v); return v; }
static inline uint8_t SHIFT_ROR(uint8_t v) { uint8_t c = fc; fc = v & 1; v = (uint8_t)((v >> 1) | (c << 7)); SETNZ(v); return v; }
static inline void PUSH(uint8_t v) { g_stk[g_sp--] = v; }
static inline uint8_t PULL(void) { return g_stk[++g_sp]; }

/* ---- tiny 6502 helpers so the lifted code keeps the exact arithmetic of the original ---- */
static inline uint8_t sbc8(uint8_t a, uint8_t m, uint8_t *c) { unsigned r = a + (uint8_t)~m + *c; *c = r > 0xFF; return (uint8_t)r; }
static inline uint8_t rd16mem(uint16_t a) { return a < 0x2000 ? g_ram[a & 0x7FF] : (a >= 0x8000 ? ROMB(a) : (a >= 0x6000 ? g_track_ext[a - 0x6000] : 0)); }   /* $6000-$7FFF: host track window (PRG-RAM area of the NES, unused by the cartridge) */
static inline uint8_t adc8(uint8_t a, uint8_t m, uint8_t *c) { unsigned r = a + m + *c; *c = r > 0xFF; return (uint8_t)r; }
#define RAM(a) g_ram[(a) & 0x7FF]
#define NEG(v) (((v) & 0x80) != 0)
