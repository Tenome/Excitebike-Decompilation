void ReadJoypadPort(Regs r) {                 /* $D35B: reads 8 bits from $4016+X, updates held/trigger bytes for that pad */
    uint8_t x = r.x, a = 0, v, c, old, x2;
    for (int i = 0; i < 8; i++) {
        v = io_r((uint16_t)(0x4016 + x));
        RAM(0x00) = v;
        c = ((uint8_t)((v >> 1) | v)) & 1;
        a = (uint8_t)((a << 1) | c);
    }
    x2 = (uint8_t)(x << 1);
    old = RAM(0x14 + x2);
    RAM(0x00) = old;
    RAM(0x14 + x2) = a;
    RAM(0x15 + x2) = a;
    if ((a & 0x80) && (old & 0x80)) RAM(0x15 + x2) = a & 0x7F;
    /* the registers the original leaves behind (the sound engine, called next from the NMI, reads some of them) */
    ra = RAM(0x15 + x2) == a ? a : (uint8_t)(a & 0x7F); rx = x2; ry = old; fc = 0; fz = ra == 0; fn = ra >> 7;
}
void ReadJoypads(void) {                      /* $D347 */
    io_w(0x4016, 1);
    io_w(0x4016, 0);
    ReadJoypadPort((Regs){ 0, 0, 0, 0 });
    ReadJoypadPort((Regs){ 0, 1, 0, 0 });
}

