static inline uint8_t rdp(uint8_t lo, uint8_t hi, uint8_t y) { return rd16mem((uint16_t)((lo | hi << 8) + y)); }   /* LDA (zp),Y */
static inline void wrmem(uint16_t a, uint8_t v) { if (a < 0x2000) g_ram[a & 0x7FF] = v; }

