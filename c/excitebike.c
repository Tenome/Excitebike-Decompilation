Regs DivModByX(Regs r) {
    uint8_t a = r.a, c = 0;
    RAM(0x0F) = r.x;
    uint8_t q = 0;
    do { q++; c = 1; a = sbc8(a, RAM(0x0F), &c); } while (!NEG(a));
    q--;
    a = adc8(a, RAM(0x0F), &c);
    return (Regs){ a, q, r.y, c };
}
Regs DivMod10(Regs r) { r.x = 10; return DivModByX(r); }

Regs IncMod64(Regs r) {
    uint8_t c = 0; uint8_t a = adc8(r.a, 1, &c);
    if (a == 0x40) a = 0;
    r.a = a; return r;
}

void UpdateRandom(void) {
    RAM(0x00) = RandomState(0) & 0x02;
    uint8_t c = ((RAM(0x19) & 0x02) ^ RAM(0x00)) ? 1 : 0;
    for (int i = 0; i < 8; i++) {
        uint8_t v = RandomState(i), nc = v & 1;
        RandomState(i) = (uint8_t)((v >> 1) | (c << 7));
        c = nc;
    }
}

void TickTimers(void) {
    uint8_t x = 0x0E;
    TimerPrescaler--;
    if (NEG(TimerPrescaler)) { TimerPrescaler = 0x0A; x = 0x1C; }
    do { if (Timers(x)) Timers(x)--; x--; } while (!NEG(x));
}

